export const generated = (source) =>
  `<!-- Generated by pnpm ai:sync from ${source}; do not edit. -->\n`;
export const header = (metadata) =>
  `---\n${Object.entries(metadata)
    .map(([key, value]) => `${key}: ${JSON.stringify(value)}`)
    .join("\n")}\n---\n\n`;
export const toml = (value) => JSON.stringify(value); // Basic single-line TOML strings use JSON escapes for these inputs.
export function command(skill, argumentsToken = "") {
  return (
    generated(skill.path) +
    `Read and follow \`${skill.path}\` completely. This explicitly invokes the ${skill.name} workflow; apply the user's request and arguments using the workflow's authorization and stop conditions.\n${argumentsToken ? `\nArguments: ${argumentsToken}\n` : ""}`
  );
}
export function roleBody(role) {
  return `Read and follow repository AGENTS.md, including its conditional rule references.\n\n${role.body}`;
}
