import { toml, roleBody } from "./common.mjs";
export const capabilities = {
  discovery: ["AGENTS.md", ".agents/skills", ".codex/agents/*.toml"],
  skills: "native canonical directories",
  commands: "native $skill-name invocation; no custom slash commands",
  rules: "native AGENTS.md; conditional explicit references",
  roles: "native standalone TOML agents (Codex 0.166.0)",
  settings: "preserved; config.toml unnecessary for standalone agents",
  hooks: "native; existing hooks.json preserved",
  mcp: "native; config.toml preserved",
  limitations: [
    "Project configuration depends on workspace trust",
    "Role instructions inherit parent runtime permissions",
  ],
};
export function render({ roles, emit }) {
  for (const role of roles)
    emit(
      `.codex/agents/${role.name}.toml`,
      `# Generated by pnpm ai:sync from ${role.path}; do not edit.\nname = ${toml(role.name)}\ndescription = ${toml(role.metadata.description)}\ndeveloper_instructions = ${toml(roleBody(role))}\n`,
    );
}
