import { command, toml, generated } from "./common.mjs";
export const capabilities = {
  discovery: ["GEMINI.md", ".agents/skills", ".gemini/commands/*.toml"],
  skills: "native .agents/skills alias",
  commands: "generated TOML wrappers; /skill-name",
  rules: "GEMINI.md imports AGENTS.md; conditional explicit references",
  roles: "partial: /role-name runs in current session, not an isolated subagent",
  settings: "preserved",
  hooks: "native; preserved",
  mcp: "native; preserved",
  limitations: [
    "Experimental custom subagents are not enabled or generated",
    "Skills can require workspace trust and activation consent",
  ],
};
export function render({ skills, roles, emit }) {
  emit("GEMINI.md", generated("AGENTS.md") + "\n@AGENTS.md\n");
  for (const skill of skills)
    emit(
      `.gemini/commands/${skill.name}.toml`,
      `# Generated by pnpm ai:sync from ${skill.path}; do not edit.\ndescription = ${toml(skill.metadata.description)}\nprompt = ${toml(command(skill, "{{args}}"))}\n`,
    );
  for (const role of roles)
    emit(
      `.gemini/commands/role-${role.name}.toml`,
      `# Generated by pnpm ai:sync from ${role.path}; do not edit.\ndescription = ${toml(role.metadata.description)}\nprompt = ${toml(`Read AGENTS.md and ${role.path}, then perform this request in the current session using that role. This is not a subagent. Request: {{args}}`)}\n`,
    );
}
