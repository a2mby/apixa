<?php

namespace Database\Seeders;

use Illuminate\Database\Seeder;
use Illuminate\Support\Facades\Storage;
use RuntimeException;

/** Explicit opt-in: creates 832 MiB of deterministic private files, never run by DatabaseSeeder. */
class LargeFileFixtureSeeder extends Seeder
{
    public function run(): void
    {
        FixtureData::guard('pgsql');
        foreach (FixtureData::read('files/file-fixtures.json')->large_files as $fixture) {
            $disk = Storage::disk('local');
            if ($disk->exists($fixture->path)) {
                $existing = $disk->readStream($fixture->path);
                $hash = hash_init('sha256');
                try {
                    hash_update_stream($hash, $existing);
                } finally {
                    fclose($existing);
                }
                if ($disk->size($fixture->path) !== $fixture->size_bytes || hash_final($hash) !== $fixture->sha256) {
                    throw new RuntimeException('Refusing to overwrite an existing large fixture with a different size.');
                }

                continue;
            }
            $stream = tmpfile();
            try {
                $chunk = str_repeat($fixture->byte, 1024 * 1024);
                for ($remaining = $fixture->size_bytes; $remaining > 0; $remaining -= strlen($bytes)) {
                    $bytes = substr($chunk, 0, min(strlen($chunk), $remaining));
                    if (fwrite($stream, $bytes) !== strlen($bytes)) {
                        throw new RuntimeException('Could not generate a large fixture.');
                    }
                }
                rewind($stream);
                $hash = hash_init('sha256');
                hash_update_stream($hash, $stream);
                if (hash_final($hash) !== $fixture->sha256) {
                    throw new RuntimeException('Generated bytes do not match the large fixture manifest.');
                }
                rewind($stream);
                if (! $disk->put($fixture->path, $stream)) {
                    throw new RuntimeException('Could not store a large fixture.');
                }
            } finally {
                fclose($stream);
            }
        }
    }
}
